// while loop example: count from 1 to 5

let i = 1; // start: the counter begins at 1

while (i <= 5) {          // condition: keep going while i is 5 or less
    console.log(i);       // this line repeats every round
    i++;                  // change: add 1 to i (without this, the loop never ends)
}

console.log("Loop finished"); // runs once, after the loop stops

// Output:
// 1
// 2
// 3
// 4
// 5
// Loop finished