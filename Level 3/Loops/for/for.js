// for loop example: count from 1 to 5

//   start      condition   change
for (let i = 1; i <= 5; i++) {
    console.log(i); // this line repeats every round
}

console.log("Loop finished"); // runs once, after the loop stops

// Output:
// 1
// 2
// 3
// 4
// 5
// Loop finished
//
