// Arithmetic operators

let a = 10;
let b = 3;

console.log(a + b); // 13 - add
console.log(a - b); // 7  - subtract
console.log(a * b); // 30 - multiply
console.log(a / b); // 3.333... - divide
console.log(a % b); // 1  - remainder (what's left after dividing)
console.log(a ** b); // 1000 - power (10 to the power of 3)